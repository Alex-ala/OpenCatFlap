#include <OCFFlapControl.h>
#include <Arduino.h>

void OCFFlapControl::init(){
    OCFLock::init(); // claims both LEDC channels once, parks both servos locked
    OCFState::loadConfig();
    OCFState::loadCats();
    stateMachineInward = new OCFStateMachine(OCFDirection::INWARD);
    stateMachineOutward = new OCFStateMachine(OCFDirection::OUTWARD);
    OCFRFID::init(stateMachineInward, stateMachineOutward);
}

void  OCFFlapControl::deinit(){

}

void  OCFFlapControl::loop(void* params){
    while(true){
        xSemaphoreTakeRecursive(loop_mutex, portMAX_DELAY);
        OCFRFID::process();
        stateMachineInward->update();
        stateMachineOutward->update();
        xSemaphoreGiveRecursive(loop_mutex);
        delay(10);
        // Idea: collect events generated by both updates, aggregate them and run handlers (save, mqtt)
    }
}

OCFMachineStates OCFFlapControl::getInwardState(){
    return stateMachineInward->getState();
}
OCFMachineStates OCFFlapControl::getOutwardState(){
    return stateMachineOutward->getState();
}

bool OCFFlapControl::suspend(){
    if (xSemaphoreTakeRecursive(loop_mutex, pdMS_TO_TICKS(1000)) != pdTRUE) return false;
    if (stateMachineInward->getState() != IDLE || stateMachineOutward->getState() != IDLE){
        xSemaphoreGiveRecursive(loop_mutex);
        return false;
    }
    return true;
}

void OCFFlapControl::resume(){
    xSemaphoreGiveRecursive(loop_mutex);
}
